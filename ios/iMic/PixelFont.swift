    static func width(_ text: String, cell: CGFloat, tracking: CGFloat) -> CGFloat {
        let count = CGFloat(text.count)
        guard count > 0 else { return 0 }
        return count * 5 * cell + max(0, count - 1) * tracking
    }

    static func fittedCell(for text: String, width: CGFloat, tracking: CGFloat = 2) -> CGFloat {
        let count = CGFloat(text.count)
        guard count > 0 else { return 0 }
        return max(1, min(16, (width - tracking * max(0, count - 1)) / (count * 5)))
    }
