struct PixelText: View {
    let text: String
    var cell: CGFloat = 3
    var color: Color = Theme.ivory
    var tracking: CGFloat = 2

    var body: some View {
        let upper = text.uppercased()
        Canvas { context, _ in
            var x: CGFloat = 0
            for character in upper {
                let glyph = PixelFont.glyphs[character] ?? PixelFont.glyphs[" "]!
                for (rowIndex, row) in glyph.enumerated() {
                    for (columnIndex, bit) in row.enumerated() where bit == "1" {
                        let rect = CGRect(
                            x: x + CGFloat(columnIndex) * cell,
                            y: CGFloat(rowIndex) * cell,
                            width: cell,
                            height: cell
                        )
                        context.fill(Path(rect), with: .color(color))
                    }
                }
                x += 5 * cell + tracking
            }
        }
        .frame(
            width: PixelFont.width(upper, cell: cell, tracking: tracking),
            height: 7 * cell,
            alignment: .topLeading
        )
        .accessibilityHidden(true)
    }
}
