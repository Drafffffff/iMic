#!/usr/bin/env python3
"""Generate CLI-only Mac resources from the apps' single translation source."""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]

def outputs():
    result = {}
    for catalog, table in [('Localizable', 'Localizable'), ('InfoPlist', 'InfoPlist')]:
        data = json.loads((ROOT / f'ios/iMic/{catalog}.xcstrings').read_text())
        for lang in ['en', 'zh-Hans']:
            lines = ['/* Generated by tools/generate-l10n.py. Edit the String Catalog. */']
            for key, entry in sorted(data['strings'].items()):
                if catalog == 'InfoPlist' and key not in MAC_INFO_KEYS:
                    continue
                # Mac and iOS use different permission descriptions with the same Info.plist keys.
                source = entry.get('comment', '')
                if catalog == 'InfoPlist' and source == 'mac':
                    key = key.removeprefix('mac.')
                value = entry['localizations'][lang]['stringUnit']['value']
                lines.append(f'{json.dumps(key, ensure_ascii=False)} = {json.dumps(value, ensure_ascii=False)};')
            result[ROOT / f'mac/Resources/{lang}.lproj/{table}.strings'] = '\n'.join(lines) + '\n'
    return result

MAC_INFO_KEYS = {'mac.NSLocalNetworkUsageDescription', 'mac.NSBluetoothAlwaysUsageDescription', 'mac.NSScreenCaptureUsageDescription', 'mac.NSHumanReadableCopyright'}
if __name__ == '__main__':
    for path, content in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
